#!/usr/bin/env bash
#
# Write a FastDDS profile that binds this machine's DDS to ONE interface, and print its path.
#
#   FASTRTPS_DEFAULT_PROFILES_FILE="$(bash scripts/laptop_dds_profile.sh 192.168.8.200)"
#
# Why (2026-09-14, docs/fact-fastdds-blocking-send.md). A laptop with Tailscale up advertises
# BOTH its Wi-Fi address and its 100.x Tailscale address as DDS unicast locators, and the Jetson's
# FastDDS then sends every user-data datagram to both: 48 Mbit/s of Wi-Fi for a 24 Mbit/s
# /cloud_registered, the second copy going tun -> tailscaled -> WireGuard -> the same Wi-Fi, or a
# DERP relay on the internet when the direct path fails. FastDDS 2.6 (Humble) cannot make the
# *sender* ignore a peer's extra locators, so the fix is here, on the machine that advertises
# them: an interfaceWhiteList of the one address the Jetson can reach. Local nodes on the laptop
# (RViz, the image decoder, the marker publisher) keep talking over shared memory.
#
# Used by scripts/laptop_viewer.sh; DDS_WHITELIST=0 there skips it.
#
set -eo pipefail
IP="${1:-}"
case "$IP" in
  ''|*[!0-9.]*) echo "usage: $0 <ipv4 address of the interface facing the Jetson>" >&2; exit 2 ;;
esac
DIR="${XDG_CACHE_HOME:-$HOME/.cache}/super-laptop-viewer"
mkdir -p "$DIR"
OUT="$DIR/fastdds_whitelist_${IP}.xml"
cat > "$OUT" <<XML
<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by scripts/laptop_dds_profile.sh: DDS on $IP only (no Tailscale locator) -->
<dds xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
  <profiles>
    <transport_descriptors>
      <transport_descriptor>
        <transport_id>udp_one_interface</transport_id>
        <type>UDPv4</type>
        <interfaceWhiteList>
          <address>$IP</address>
        </interfaceWhiteList>
      </transport_descriptor>
      <transport_descriptor>
        <transport_id>shm_local</transport_id>
        <type>SHM</type>
      </transport_descriptor>
    </transport_descriptors>
    <participant profile_name="laptop_one_interface" is_default_profile="true">
      <rtps>
        <userTransports>
          <transport_id>udp_one_interface</transport_id>
          <transport_id>shm_local</transport_id>
        </userTransports>
        <useBuiltinTransports>false</useBuiltinTransports>
      </rtps>
    </participant>
  </profiles>
</dds>
XML
echo "$OUT"
